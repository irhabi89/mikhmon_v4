<?php

session_start();
// hide all error
error_reporting(0);
// protect .php
$get_self = explode("/", $_SERVER['PHP_SELF']);
$self[] = $get_self[count($get_self) - 1];

if ($self[0] !== "index.php" && $self[0] !== "") {
    include_once("../core/route.php");
} else {
    include_once("config/connection.php");

    $prof = $_GET['prof'] ?? 'all';
    $comm = $_GET['comm'] ?? '';
    $export = $_GET['export'] ?? 'csv';

    $params = array();
    if (!empty($prof) && $prof !== 'all' && $prof !== 'Profile') {
        $params['?profile'] = $prof;
    }
    if (!empty($comm) && $comm !== 'Comment') {
        $params['?comment'] = $comm;
    }

    if (!empty($params)) {
        $get_users = $API->comm("/ip/hotspot/user/print", $params);
    } else {
        $get_users = $API->comm("/ip/hotspot/user/print");
    }

    if (!is_array($get_users)) {
        $get_users = array();
    }

    $date_str = date("Y-m-d");

    if ($export === "rsc" || $export === "script") {
        header("Content-Type: text/plain; charset=utf-8");
        header('Content-Disposition: attachment; filename="hotspot-users-' . $m_user . '-' . $date_str . '.rsc"');

        echo "# Generated by MIKHMON v4\n";
        echo "# Export Hotspot Users - " . $date_str . "\n";
        echo "/ip hotspot user\n";

        foreach ($get_users as $u) {
            $name = $u['name'] ?? '';
            if (empty($name)) continue;
            $pass = $u['password'] ?? '';
            $profile = $u['profile'] ?? 'default';
            $server = $u['server'] ?? 'all';
            $comment = $u['comment'] ?? '';
            $timelimit = $u['limit-uptime'] ?? '';
            $datalimit = $u['limit-bytes-total'] ?? '';

            $line = 'add name="' . $name . '"';
            if ($pass !== '') {
                $line .= ' password="' . $pass . '"';
            }
            if ($profile !== '') {
                $line .= ' profile="' . $profile . '"';
            }
            if ($server !== '' && $server !== 'all') {
                $line .= ' server="' . $server . '"';
            }
            if ($comment !== '') {
                $line .= ' comment="' . $comment . '"';
            }
            if ($timelimit !== '') {
                $line .= ' limit-uptime="' . $timelimit . '"';
            }
            if ($datalimit !== '' && $datalimit !== '0') {
                $line .= ' limit-bytes-total="' . $datalimit . '"';
            }
            echo $line . "\n";
        }
        exit;
    } else {
        // CSV Export
        header("Content-Type: text/csv; charset=utf-8");
        header('Content-Disposition: attachment; filename="hotspot-users-' . $m_user . '-' . $date_str . '.csv"');

        $out = fopen('php://output', 'w');
        fputcsv($out, array('Username', 'Password', 'Profile', 'Server', 'Time Limit', 'Data Limit', 'Comment'));

        foreach ($get_users as $u) {
            $name = $u['name'] ?? '';
            if (empty($name)) continue;
            $pass = $u['password'] ?? '';
            $profile = $u['profile'] ?? 'default';
            $server = $u['server'] ?? 'all';
            $comment = $u['comment'] ?? '';
            $timelimit = $u['limit-uptime'] ?? '';
            $datalimit = $u['limit-bytes-total'] ?? '';

            fputcsv($out, array($name, $pass, $profile, $server, $timelimit, $datalimit, $comment));
        }
        fclose($out);
        exit;
    }
}
